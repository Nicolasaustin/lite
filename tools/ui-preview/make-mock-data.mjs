const SC_EXT = {
  28: 'Num Enter', 29: 'R Ctrl', 53: 'Num /', 55: 'PrtSc', 56: 'R Alt', 71: 'Home', 72: 'Up',
  73: 'Page Up', 75: 'Left', 77: 'Right', 79: 'End', 80: 'Down', 81: 'Page Down', 82: 'Insert',
  83: 'Delete', 91: 'L Win', 92: 'R Win', 93: 'Menu'
};
const scLabel = (sc, ext) => (ext ? SC_EXT[sc] : SC[sc]) || `Scan ${sc}${ext ? ' (ext)' : ''}`;

const profiles = load('profiles.json', { Mouse: [], Keyboard: [], Macros: [] });
const games = load('games.json', []);
const calib = load('calibration.json', {});
const onboard = load('onboard.json', {});
const settings = load('settings.json', {});
const log = load('log.txt', '');

const mouseProfiles = (profiles.Mouse || []).map(p => ({
  name: p.Name,
  pollingRate: p.PollingRate ?? 1000,
  dpi: p.Dpi ?? 800,
  dpiStages: p.DpiStages?.length ? p.DpiStages : [p.Dpi ?? 800],
  dpiActive: p.DpiActive ?? 1,
  buttons: Object.fromEntries(Object.entries(p.Buttons || {}).map(([id, t]) => [id, { key: t.Key, mods: t.Mods || [] }]))
}));

const keyboardProfiles = (profiles.Keyboard || []).map(p => ({
  name: p.Name,
  brightness: p.Brightness ?? 100,
  snapTap: !!p.SnapTap,
  macroKeys: { ...(p.MacroKeys || {}) },
  effect: p.Effect || 'static',
  effectSpeed: p.EffectSpeed || 2
}));

const macros = (profiles.Macros || []).map(m => ({
  name: m.Name,
  steps: (m.Steps || []).map(s => ({ vk: s.Vk, ext: !!s.Ext, down: !!s.Down, delayMs: s.DelayMs || 0 }))
}));

const gameRows = games.map(g => ({ profile: g.Profile, exes: g.Exes || [], keyboardProfile: g.KeyboardProfile || '' }));

const calibration = Object.fromEntries(Object.entries(calib).map(([id, b]) => [id, scLabel(b.Sc, b.Ext)]));

const buttonIds = [...Array.from({ length: 12 }, (_, i) => `Side${i + 1}`), 'Scroll', 'M1', 'M2', 'TiltL', 'TiltR'];

const defaultMouse = settings.DefaultMouse || mouseProfiles[0]?.name || '';
const defaultKeyboard = settings.DefaultKeyboard || keyboardProfiles[0]?.name || '';

const state = {
  version: '1.1.0',
  mouse: { connected: true, name: 'Naga Left-Handed Edition' },
  keyboard: { connected: true, name: 'BlackWidow Lite' },
  auto: true,
  inGame: true,
  liveWrite: true,
  startup: true,
  liveStatus: `"${defaultMouse}" is running on the mouse (slot 1, White)`,
  activeMouse: defaultMouse,
  activeKeyboard: defaultKeyboard,
  defaultMouse,
  defaultKeyboard,
  mouseProfiles,
  keyboardProfiles,
  macros,
  games: gameRows,
  calibration,
  buttonIds,
  onboard,
  liveSlots: [1, 2],
  mouseLighting: { effect: 'static', color: '#00FF66', brightness: 100, zones: [0] },
  accent: 'mint'
};

const out = {
  _source: 'Generated by make-mock-data.mjs from LiteSynapse/data — preview only.',
  state,
  runningApps: ['Discord.exe', 'Spotify.exe', 'Steam.exe', 'chrome.exe', 'cs2.exe', 'explorer.exe', 'obs64.exe', 'steamwebhelper.exe'],
  deviceInfo: { mouse: { dpi: 800, polling: 1000, slot: 1, slotName: 'White' }, keyboard: { brightness: 7 } },
  lightingZones: [
    { id: 0, name: 'All zones' }, { id: 1, name: 'Scroll wheel' }, { id: 2, name: 'Logo' }, { id: 3, name: 'Side panel' }
  ],
  log: String(log).replace(/\r\n/g, '\n')
};

const dest = join(here, 'mock-data.json');
writeFileSync(dest, JSON.stringify(out, null, 2) + '\n');
console.log(`wrote ${dest}: ${mouseProfiles.length} mouse, ${keyboardProfiles.length} keyboard, ${macros.length} macros, ${gameRows.length} games, ${Object.keys(calibration).length} calibrated`);
